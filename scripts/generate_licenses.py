#!/usr/bin/env python3
"""Regenerates THIRD_PARTY_LICENSES.md from the licence files in the pinned package checkouts.
Run after dependencies change (and after a build, so build/DerivedData/SourcePackages exists):  python3 scripts/generate_licenses.py
The list of packages in ROWS is maintained by hand: check it against Package.resolved and the linked binary."""
import json, os, sys
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
C = "build/DerivedData/SourcePackages/checkouts/"
pins = {p["identity"]: p for p in json.load(open("Package.resolved"))["pins"]}

def ver(i):
    st = pins[i]["state"]
    return st.get("version") or ("revision " + st["revision"][:12])

def read(p):
    return open(C + p).read().strip("\n")

# (display name, package identity, licence, copyright or source, bundled-inside-another-package?)
ROWS = [
    ("FluidAudio", "fluidaudio", "Apache-2.0", "https://github.com/FluidInference/FluidAudio (speech recognition only; its other parts are switched off)", False),
    ("fastcluster (bundled in FluidAudio)", "fluidaudio", "BSD-2-Clause", "© Daniel Müllner; © Google Inc. (text below)", True),
    ("mlx-swift", "mlx-swift", "MIT", "© ml-explore; https://github.com/ml-explore/mlx-swift", False),
    ("MLX C++ core (bundled in mlx-swift)", "mlx-swift", "MIT", "© Apple Inc.", True),
    ("mlx-c (bundled in mlx-swift)", "mlx-swift", "MIT", "© ml-explore", True),
    ("metal-cpp (bundled in mlx-swift)", "mlx-swift", "Apache-2.0", "Apple Inc.", True),
    ("{fmt} (bundled in mlx-swift)", "mlx-swift", "MIT", "© Victor Zverovich and {fmt} contributors", True),
    ("JSON for Modern C++ (bundled in mlx-swift)", "mlx-swift", "MIT", "© Niels Lohmann", True),
    ("mlx-swift-lm", "mlx-swift-lm", "MIT", "© ml-explore; https://github.com/ml-explore/mlx-swift-lm", False),
    ("swift-transformers", "swift-transformers", "Apache-2.0", "© 2022 Hugging Face SAS; https://github.com/huggingface/swift-transformers", False),
    ("swift-huggingface", "swift-huggingface", "Apache-2.0", "© 2025 Hugging Face SAS; https://github.com/huggingface/swift-huggingface", False),
    ("swift-jinja", "swift-jinja", "Apache-2.0", "© 2022 Hugging Face SAS; https://github.com/huggingface/swift-jinja", False),
    ("EventSource", "eventsource", "MIT", "© 2025 Mattt", False),
    ("swift-crypto", "swift-crypto", "Apache-2.0", "© The SwiftCrypto Project (notice below)", False),
    ("swift-asn1", "swift-asn1", "Apache-2.0", "© The SwiftASN1 Project (notice below)", False),
    ("swift-collections", "swift-collections", "Apache-2.0 with Runtime Library Exception", "https://github.com/apple/swift-collections", False),
    ("swift-numerics", "swift-numerics", "Apache-2.0 with Runtime Library Exception", "https://github.com/apple/swift-numerics", False),
    ("yyjson", "yyjson", "MIT", "© 2020 YaoYuan", False),
]
MIT_FILES = [("EventSource", "EventSource/LICENSE.md"), ("mlx-swift", "mlx-swift/LICENSE"), ("mlx-swift-lm", "mlx-swift-lm/LICENSE"),
             ("MLX C++ core", "mlx-swift/Source/Cmlx/mlx/LICENSE"), ("mlx-c", "mlx-swift/Source/Cmlx/mlx-c/LICENSE"),
             ("{fmt}", "mlx-swift/Source/Cmlx/fmt/LICENSE"), ("JSON for Modern C++", "mlx-swift/Source/Cmlx/json/LICENSE.MIT"), ("yyjson", "yyjson/LICENSE")]

out = []
w = out.append
w("# Third-party licences\n")
w("This file lists the open-source code and the machine-learning models that Voice It uses, with their licences. "
  "Voice It itself is licensed under the GNU General Public License, version 3 (see LICENSE). It is generated by `scripts/generate_licenses.py` from the licence files in the exact "
  "package versions this build uses (`Package.resolved`); regenerate it when a dependency changes. It reflects the build with FluidAudio's text-to-speech, "
  "speaker-diarization and NeMo text-normalisation parts switched off (`traits: []`).\n")
w("## Models\n")
w("The models are not part of the app and are not redistributed by this project: the setup window (or `scripts/setup-models.sh`) downloads them once, at pinned revisions, from the original hosts on Hugging Face, and checks every file against a checksum. They run locally with no network access. The licence declared on each model's card was last checked on 31 October 2026: `cc-by-4.0` for the Parakeet model (its card says \"Use of this model is governed by the CC-BY-4.0 license\") and `apache-2.0` for the Qwen model.\n")
w("### Parakeet TDT 0.6B v2 (speech recognition): CC BY 4.0\n")
w("- Original model: *parakeet-tdt-0.6b-v2* by NVIDIA, https://huggingface.co/nvidia/parakeet-tdt-0.6b-v2, licensed under the Creative Commons Attribution 4.0 International licence (CC BY 4.0), https://creativecommons.org/licenses/by/4.0/")
w("- Core ML conversion used here: https://huggingface.co/FluidInference/parakeet-tdt-0.6b-v2-coreml by FluidInference, also CC BY 4.0 (pinned revision `ee09c569f737`).")
w("- Changes: converted to Core ML format and run on the Apple Neural Engine through FluidAudio. No further modification.\n")
w("### Qwen3-4B-Instruct-2507 (text cleanup): Apache-2.0\n")
w("- Original model: *Qwen3-4B-Instruct-2507* by the Qwen Team (Alibaba Cloud), https://huggingface.co/Qwen/Qwen3-4B-Instruct-2507, Apache License 2.0 (full text below).")
w("- 4-bit MLX conversion used here: https://huggingface.co/mlx-community/Qwen3-4B-Instruct-2507-4bit by mlx-community, Apache-2.0 (pinned revision `50d427756c6b`).")
w("- Changes: quantised to 4 bits for MLX. No further modification.\n")
w("## Artwork\n")
w("The app icon and the menu bar icons (the `design/icons` folder) are original artwork made for this project. They are part of this repository and are distributed under the same licence as the rest of it, the GNU General Public License, version 3.\n")
w("## Code in the app\n")
w("| Package | Version | Licence | Copyright / source |\n| --- | --- | --- | --- |")
for name, ident, lic, cr, bundled in ROWS:
    w(f"| {'↳ ' if bundled else ''}{name} | {'(bundled)' if bundled else ver(ident)} | {lic} | {cr} |")
w("")
w("Fetched by the package manager but **not compiled into the app**: swift-syntax (Apache-2.0). Parts of FluidAudio that are switched off in this build "
  "(text-to-speech, speaker diarization, the NeMo text-normalisation engine) and the third-party code and licences that belong to them (Kokoro, "
  "G2P resources, VBx, NeMo Text Processing) are not in the app. Apple's own frameworks (Core ML, AVFoundation, SwiftUI, Accelerate and so on) come with macOS.\n")
w("## Licence texts\n")
w("### Apache License 2.0\n")
w("Applies to: FluidAudio, metal-cpp, swift-transformers, swift-huggingface, swift-jinja, swift-crypto, swift-asn1, swift-collections, swift-numerics, "
  "and the Qwen3-4B-Instruct-2507 model. This is the standard Apache-2.0 text; the projects' own licence files are identical to it apart from the "
  "copyright line some of them append (credited in the table above).\n")
w("```text\n" + read("swift-crypto/LICENSE.txt") + "\n```\n")
w("### Runtime Library Exception to the Apache 2.0 License\n")
w("Applies to swift-collections and swift-numerics (text from their licence files):\n")
t = read("swift-collections/LICENSE.txt"); i = t.find("## Runtime Library Exception")
assert i > 0
w("```text\n" + t[i:].strip() + "\n```\n")
w("### MIT licences\n")
for title, path in MIT_FILES:
    w(f"#### {title}\n\n```text\n{read(path)}\n```\n")
w("### BSD 2-Clause: fastcluster\n")
w("```text\n" + read("FluidAudio/ThirdPartyLicenses/fastcluster-LICENSE.md") + "\n```\n")
w("### Notices\n")
for title, path in [("swift-crypto (NOTICE.txt)", "swift-crypto/NOTICE.txt"), ("swift-asn1 (NOTICE.txt)", "swift-asn1/NOTICE.txt")]:
    w(f"#### {title}\n\n```text\n{read(path)}\n```\n")
open("THIRD_PARTY_LICENSES.md", "w").write("\n".join(out) + "\n")
print("wrote THIRD_PARTY_LICENSES.md,", len(out), "blocks")
